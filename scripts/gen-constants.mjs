// Writes assembly/constants.ts: the round constants and start values of MD5, SHA-256 and SHA-512, computed from
// their definitions instead of typed by hand. SHA-2 values are exact (integer roots with BigInt); MD5's are
// floor(|sin(i + 1)| × 2^32) as RFC 1321 defines them.
import {writeFileSync} from "node:fs";

function primes(count) {
  const found = [];
  for (let n = 2; found.length < count; n++) if (found.every((p) => n % p !== 0)) found.push(n);
  return found.map(BigInt);
}

function integerRoot(value, k) {
  // Largest x with x^k <= value (Newton's method on BigInt).
  if (value < 2n) return value;
  let x = 1n << BigInt(Math.ceil(value.toString(2).length / k));
  for (;;) {
    const next = ((BigInt(k) - 1n) * x + value / x ** (BigInt(k) - 1n)) / BigInt(k);
    if (next >= x) break;
    x = next;
  }
  while (x ** BigInt(k) > value) x -= 1n;
  while ((x + 1n) ** BigInt(k) <= value) x += 1n;
  return x;
}

// The first `bits` bits of the fractional part of the k-th root of p.
const fraction = (p, k, bits) => integerRoot(p << BigInt(bits * k), k) & ((1n << BigInt(bits)) - 1n);

const p80 = primes(80);
const hex = (v, digits) => "0x" + v.toString(16).padStart(digits, "0");
const list = (values) => values.map((v, i) => (i % 4 === 0 ? "\n  " : " ") + v + ",").join("");

const md5 = Array.from({length: 64}, (_, i) => BigInt(Math.floor(Math.abs(Math.sin(i + 1)) * 2 ** 32)));
const sha256K = p80.slice(0, 64).map((p) => fraction(p, 3, 32));
const sha256H = p80.slice(0, 8).map((p) => fraction(p, 2, 32));
const sha512K = p80.map((p) => fraction(p, 3, 64));
const sha512H = p80.slice(0, 8).map((p) => fraction(p, 2, 64));

const out = `// Generated by scripts/gen-constants.mjs. Do not edit by hand.

export const MD5_K: StaticArray<u32> = [${list(md5.map((v) => hex(v, 8)))}
];

export const SHA256_K: StaticArray<u32> = [${list(sha256K.map((v) => hex(v, 8)))}
];

export const SHA256_H: StaticArray<u32> = [${list(sha256H.map((v) => hex(v, 8)))}
];

export const SHA512_K: StaticArray<u64> = [${list(sha512K.map((v) => hex(v, 16)))}
];

export const SHA512_H: StaticArray<u64> = [${list(sha512H.map((v) => hex(v, 16)))}
];
`;
writeFileSync(new URL("../assembly/constants.ts", import.meta.url), out);
console.log("assembly/constants.ts written", sha256K[0].toString(16), sha512K[79].toString(16), md5[0].toString(16));
